//! The Go summary script, embedded so there is no separate file to locate at
//! runtime.
//!
//! WitDiff writes this beside a copy of the target file and runs it with
//! `go run` (ADR-0017). Go's parser lives in the standard library, so no
//! dependency is needed on either side.

/// The script's format version.
pub const SUMMARY_FORMAT: u32 = 1;

/// Emit a normalized structural summary of one Go test file as JSON.
pub const SUMMARY_SCRIPT: &str = concat!(
    "// Summary script for Go test files. Run with `go run` from a temporary\n",
    "// directory containing only this file and the target (ADR-0017).\n",
    "package main\n",
    "\n",
    "import (\n",
    "	\"encoding/json\"\n",
    "	\"fmt\"\n",
    "	\"go/ast\"\n",
    "	\"go/parser\"\n",
    "	\"go/token\"\n",
    "	\"os\"\n",
    "	\"strings\"\n",
    ")\n",
    "\n",
    "// normalize renders an expression to a stable, formatting-insensitive form.\n",
    "// Deliberately not go/printer: this form is ours and both sides are versioned\n",
    "// together, so a toolchain change cannot alter the comparison.\n",
    "func normalize(e ast.Expr) string {\n",
    "	switch n := e.(type) {\n",
    "	case *ast.BasicLit:\n",
    "		return n.Value\n",
    "	case *ast.Ident:\n",
    "		return n.Name\n",
    "	case *ast.SelectorExpr:\n",
    "		return normalize(n.X) + \".\" + n.Sel.Name\n",
    "	case *ast.CallExpr:\n",
    "		parts := []string{}\n",
    "		for _, a := range n.Args {\n",
    "			parts = append(parts, normalize(a))\n",
    "		}\n",
    "		return normalize(n.Fun) + \"(\" + strings.Join(parts, \", \") + \")\"\n",
    "	case *ast.BinaryExpr:\n",
    "		return normalize(n.X) + \" \" + n.Op.String() + \" \" + normalize(n.Y)\n",
    "	case *ast.UnaryExpr:\n",
    "		return n.Op.String() + normalize(n.X)\n",
    "	case *ast.ParenExpr:\n",
    "		return normalize(n.X)\n",
    "	case *ast.IndexExpr:\n",
    "		return normalize(n.X) + \"[\" + normalize(n.Index) + \"]\"\n",
    "	case *ast.CompositeLit:\n",
    "		parts := []string{}\n",
    "		for _, el := range n.Elts {\n",
    "			parts = append(parts, normalize(el))\n",
    "		}\n",
    "		return \"{\" + strings.Join(parts, \", \") + \"}\"\n",
    "	case *ast.StarExpr:\n",
    "		return \"*\" + normalize(n.X)\n",
    "	case *ast.KeyValueExpr:\n",
    "		return normalize(n.Key) + \": \" + normalize(n.Value)\n",
    "	case *ast.TypeAssertExpr:\n",
    "		return normalize(n.X) + \".(type)\"\n",
    "	case *ast.SliceExpr:\n",
    "		return normalize(n.X) + \"[:]\"\n",
    "	}\n",
    "	return fmt.Sprintf(\"%T\", e)\n",
    "}\n",
    "\n",
    "type assertion struct {\n",
    "	Line int    `json:\"line\"`\n",
    "	Test string `json:\"test\"`\n",
    "}\n",
    "\n",
    "type function struct {\n",
    "	Name       string      `json:\"name\"`\n",
    "	Line       int         `json:\"line\"`\n",
    "	Assertions []assertion `json:\"assertions\"`\n",
    "	Skipped    bool        `json:\"skipped\"`\n",
    "	Empty      bool        `json:\"body_is_empty\"`\n",
    "	Bindings   map[string]string `json:\"bindings\"`\n",
    "}\n",
    "\n",
    "// testifyCall renders an assert/require call as the comparison it makes, or\n",
    "// returns \"\" when the call is not one of them.\n",
    "//\n",
    "// testify is the most used Go assertion library, and its calls are not\n",
    "// `t.Error*`, so failureCall never saw them. A testify-only test summarized\n",
    "// with zero assertions and zero guards, which made deleting its last\n",
    "// assertion indistinguishable from an unchanged test. Measured before this\n",
    "// function existed: assert.Equal, require.NoError and assert.True each\n",
    "// yielded [] while a plain `if` guard in the same file was found.\n",
    "//\n",
    "// Every function takes (t, ...) first, so the comparison operands are the\n",
    "// arguments after that. assert is non-fatal and require aborts, but both\n",
    "// assert the same thing, so they render identically — as `t.Fatal` does.\n",
    "func testifyCall(call *ast.CallExpr) string {\n",
    "\tsel, ok := call.Fun.(*ast.SelectorExpr)\n",
    "\tif !ok {\n",
    "\t\treturn \"\"\n",
    "\t}\n",
    "\tpkg, ok := sel.X.(*ast.Ident)\n",
    "\tif !ok || (pkg.Name != \"assert\" && pkg.Name != \"require\") {\n",
    "\t\treturn \"\"\n",
    "\t}\n",
    "\targs := call.Args\n",
    "\tif len(args) < 2 {\n",
    "\t\t// A one-argument call asserts about the testing.T alone, which is\n",
    "\t\t// never what the author meant.\n",
    "\t\treturn \"\"\n",
    "\t}\n",
    "\t// Drop the leading `t` and keep the rest as the operands.\n",
    "\toperands := args[1:]\n",
    "\tfirst := normalize(operands[0])\n",
    "\tname := sel.Sel.Name\n",
    "\n",
    "\tswitch name {\n",
    "\tcase \"Equal\", \"Exactly\", \"EqualValues\", \"Equalf\", \"Exactlyf\":\n",
    "\t\t// (expected, actual) — the same order as a binary comparison.\n",
    "\t\tif len(operands) < 2 {\n",
    "\t\t\treturn first\n",
    "\t\t}\n",
    "\t\treturn normalize(operands[1]) + \" Eq \" + first\n",
    "\tcase \"NotEqual\", \"NotEqualValues\", \"NotEqualf\":\n",
    "\t\tif len(operands) < 2 {\n",
    "\t\t\treturn first\n",
    "\t\t}\n",
    "\t\treturn normalize(operands[1]) + \" NotEq \" + first\n",
    "\tcase \"True\", \"Truef\":\n",
    "\t\treturn first\n",
    "\tcase \"False\", \"Falsef\":\n",
    "\t\treturn \"Not \" + first\n",
    "\tcase \"Nil\", \"Nilf\":\n",
    "\t\treturn first + \" Is nil\"\n",
    "\tcase \"NotNil\", \"NotNilf\":\n",
    "\t\treturn first + \" IsNot nil\"\n",
    "\tcase \"Greater\", \"GreaterOrEqual\", \"Less\", \"LessOrEqual\":\n",
    "\t\tif len(operands) < 2 {\n",
    "\t\t\treturn first\n",
    "\t\t}\n",
    "\t\top := map[string]string{\n",
    "\t\t\t\"Greater\": \"Gt\", \"GreaterOrEqual\": \"Gte\",\n",
    "\t\t\t\"Less\": \"Lt\", \"LessOrEqual\": \"Lte\",\n",
    "\t\t}[name]\n",
    "\t\treturn normalize(operands[1]) + \" \" + op + \" \" + first\n",
    "\tcase \"Contains\", \"NotContains\":\n",
    "\t\t// (haystack, needle): the subject is the first operand.\n",
    "\t\tif len(operands) < 2 {\n",
    "\t\t\treturn first\n",
    "\t\t}\n",
    "\t\top := \"Contains\"\n",
    "\t\tif name == \"NotContains\" {\n",
    "\t\t\top = \"NotContains\"\n",
    "\t\t}\n",
    "\t\treturn first + \" \" + op + \" \" + normalize(operands[1])\n",
    "\tcase \"Len\":\n",
    "\t\treturn \"len(\" + first + \")\"\n",
    "\tcase \"NoError\", \"NoErrorf\":\n",
    "\t\treturn first + \" NotEq nil\"\n",
    "\t// require.Error / assert.Error / EqualError name a failure that must\n",
    "\t// happen rather than a value to compare. They constrain the test exactly\n",
    "\t// as an exception expectation does in the other analyzers, and reuse that\n",
    "\t// rendering so the shared engine counts them as assertions.\n",
    "\tcase \"Error\", \"Errorf\", \"EqualError\":\n",
    "\t\treturn \"expects-exception\"\n",
    "\t}\n",
    "\t// An unrecognised assert/require call still constrains the test, so it\n",
    "\t// counts as an assertion; rendering it as the bare first operand keeps\n",
    "\t// the subject without inventing a comparison that was not written.\n",
    "\treturn first\n",
    "}\n",
    "\n",
    "// failureCall reports whether a call is a test failure report, and returns the\n",
    "// expression that was checked when one can be identified.\n",
    "//\n",
    "// Go has no assertion keyword: a test fails by calling t.Error, t.Errorf,\n",
    "// t.Fatal, t.Fatalf, or t.Fail. The meaningful part is the *condition* that\n",
    "// guarded the call, so the enclosing `if` is what gets normalized.\n",
    "func failureCall(call *ast.CallExpr) bool {\n",
    "	sel, ok := call.Fun.(*ast.SelectorExpr)\n",
    "	if !ok {\n",
    "		return false\n",
    "	}\n",
    "	switch sel.Sel.Name {\n",
    "	case \"Error\", \"Errorf\", \"Fatal\", \"Fatalf\", \"Fail\", \"FailNow\":\n",
    "		return true\n",
    "	}\n",
    "	return false\n",
    "}\n",
    "\n",
    "// guardOf walks up from a failure call to find the condition guarding it.\n",
    "// Go's idiom is `if got != want { t.Errorf(...) }`, so the `if` condition is\n",
    "// the assertion.\n",
    "func guardOf(root ast.Node, target *ast.CallExpr) ast.Expr {\n",
    "	var found ast.Expr\n",
    "	ast.Inspect(root, func(n ast.Node) bool {\n",
    "		ifStmt, ok := n.(*ast.IfStmt)\n",
    "		if !ok {\n",
    "			return true\n",
    "		}\n",
    "		ast.Inspect(ifStmt.Body, func(inner ast.Node) bool {\n",
    "			if inner == target {\n",
    "				found = ifStmt.Cond\n",
    "				return false\n",
    "			}\n",
    "			return true\n",
    "		})\n",
    "		return found == nil\n",
    "	})\n",
    "	return found\n",
    "}\n",
    "\n",
    "func main() {\n",
    "	if len(os.Args) != 2 {\n",
    "		fmt.Fprintln(os.Stderr, \"usage: summarize <path>\")\n",
    "		os.Exit(2)\n",
    "	}\n",
    "	fset := token.NewFileSet()\n",
    "	file, err := parser.ParseFile(fset, os.Args[1], nil, parser.ParseComments)\n",
    "	if err != nil {\n",
    "		json.NewEncoder(os.Stdout).Encode(map[string]any{\"format\": 1, \"error\": err.Error()})\n",
    "		return\n",
    "	}\n",
    "\n",
    "	functions := []function{}\n",
    "	for _, decl := range file.Decls {\n",
    "		fn, ok := decl.(*ast.FuncDecl)\n",
    "		if !ok || fn.Body == nil {\n",
    "			continue\n",
    "		}\n",
    "		// Go collects any function named TestXxx or BenchmarkXxx.\n",
    "		if !strings.HasPrefix(fn.Name.Name, \"Test\") && !strings.HasPrefix(fn.Name.Name, \"Benchmark\") {\n",
    "			continue\n",
    "		}\n",
    "\n",
    "		assertions := []assertion{}\n",
    "		ast.Inspect(fn.Body, func(n ast.Node) bool {\n",
    "			call, ok := n.(*ast.CallExpr)\n",
    "			if !ok {\n",
    "				return true\n",
    "			}\n",
    "			// A testify assert/require call is the assertion itself: there\n",
    "			// is no enclosing guard to find, and no failure call either.\n",
    "			if rendered := testifyCall(call); rendered != \"\" {\n",
    "				assertions = append(assertions, assertion{\n",
    "					Line: fset.Position(call.Pos()).Line,\n",
    "					Test: rendered,\n",
    "				})\n",
    "				return true\n",
    "			}\n",
    "			if !failureCall(call) {\n",
    "				return true\n",
    "			}\n",
    "			test := \"t.Fail()\"\n",
    "			if guard := guardOf(fn.Body, call); guard != nil {\n",
    "				test = normalize(guard)\n",
    "			} else if len(call.Args) > 0 {\n",
    "				test = \"t.Error(\" + normalize(call.Args[0]) + \")\"\n",
    "			}\n",
    "			assertions = append(assertions, assertion{\n",
    "				Line: fset.Position(call.Pos()).Line,\n",
    "				Test: test,\n",
    "			})\n",
    "			return true\n",
    "		})\n",
    "\n",
    "		// A test that calls t.Skip no longer checks anything, which is the Go\n",
    "		// equivalent of Rust's #[ignore] and Python's pytest.mark.skip.\n",
    "		skipped := false\n",
    "		ast.Inspect(fn.Body, func(n ast.Node) bool {\n",
    "			call, ok := n.(*ast.CallExpr)\n",
    "			if !ok {\n",
    "				return true\n",
    "			}\n",
    "			if sel, ok := call.Fun.(*ast.SelectorExpr); ok {\n",
    "				if sel.Sel.Name == \"Skip\" || sel.Sel.Name == \"Skipf\" || sel.Sel.Name == \"SkipNow\" {\n",
    "					skipped = true\n",
    "				}\n",
    "			}\n",
    "			return true\n",
    "		})\n",
    "\n",
    "		// Simple bindings, so the analyzer can recognize a rebound\n",
    "		// subject: `v := compute(); if v != 4` asserts the same thing as\n",
    "		// `if compute() != 4`. Only single-name targets are recorded;\n",
    "		// redeclaration is left unresolved, which keeps the conservative\n",
    "		// direction.\n",
    "		bindings := map[string]string{}\n",
    "		seen := map[string]bool{}\n",
    "		ast.Inspect(fn.Body, func(n ast.Node) bool {\n",
    "			assign, ok := n.(*ast.AssignStmt)\n",
    "			if !ok || len(assign.Lhs) != 1 || len(assign.Rhs) != 1 {\n",
    "				return true\n",
    "			}\n",
    "			ident, ok := assign.Lhs[0].(*ast.Ident)\n",
    "			if !ok || ident.Name == \"_\" {\n",
    "				return true\n",
    "			}\n",
    "			if seen[ident.Name] {\n",
    "				delete(bindings, ident.Name)\n",
    "				return true\n",
    "			}\n",
    "			seen[ident.Name] = true\n",
    "			bindings[ident.Name] = normalize(assign.Rhs[0])\n",
    "			return true\n",
    "		})\n",
    "		empty := len(fn.Body.List) == 0\n",
    "		functions = append(functions, function{\n",
    "			Name:       fn.Name.Name,\n",
    "			Line:       fset.Position(fn.Pos()).Line,\n",
    "			Assertions: assertions,\n",
    "			Skipped:    skipped,\n",
    "			Empty:      empty,\n",
    "			Bindings:   bindings,\n",
    "		})\n",
    "	}\n",
    "	json.NewEncoder(os.Stdout).Encode(map[string]any{\"format\": 1, \"functions\": functions})\n",
    "}\n",
    "\n",
);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_script_has_the_expected_shape() {
        assert!(SUMMARY_SCRIPT.contains("go/parser"));
        assert!(SUMMARY_SCRIPT.contains("go/ast"));
        assert!(SUMMARY_SCRIPT.contains("func main()"));
    }

    /// Go has no assertion keyword, so the guard condition is the assertion.
    /// If that logic went missing the analyzer would compare error messages.
    #[test]
    fn the_script_looks_for_guarding_conditions() {
        assert!(SUMMARY_SCRIPT.contains("func guardOf"));
        assert!(SUMMARY_SCRIPT.contains("*ast.IfStmt"));
    }

    #[test]
    fn the_script_detects_skips() {
        assert!(SUMMARY_SCRIPT.contains(r#""Skip""#));
    }
}
